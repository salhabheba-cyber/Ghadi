import { describe, expect, it, vi } from "vitest";
import { buildPrompt, extractJson, parseTaskOutput } from "@/lib/ai/tasks";
import { createHostedProvider } from "@/lib/ai/hosted-client";
import { generateWithFallback } from "@/lib/ai/registry";
import { ProviderError } from "@/lib/ai/types";
import { settingsSchema } from "@/lib/validation/schemas";
import { readHostedConfig } from "@/lib/server/hosted-config";

const SOURCE =
  "Photosynthesis is the process by which plants make sugar from light. Chlorophyll absorbs light energy for the plant.";
const goodQuiz = JSON.stringify({
  questions: [
    {
      type: "mcq",
      prompt: "What absorbs light?",
      options: ["Chlorophyll", "Water", "Soil"],
      correct: "Chlorophyll",
      explanation: "From the source.",
      difficulty: "easy",
    },
    {
      type: "tf",
      prompt: "Plants make sugar from light.",
      options: ["True", "False"],
      correct: "True",
      explanation: "",
    },
  ],
});

describe("prompts and output validation", () => {
  it("builds prompts that treat the source as untrusted data and demand JSON only", () => {
    const p = buildPrompt("quiz", {
      title: "T",
      text: SOURCE,
      count: 3,
      difficulty: "easy",
      types: ["mcq"],
    });
    expect(p.system).toMatch(/untrusted data/);
    expect(p.system).toMatch(/Never invent/);
    expect(p.user).toContain("<source");
    expect(p.user).toContain("Write 3 quiz questions");
  });

  it("tells the model not to invent subjects or repair unclear text, and to keep worksheet questions apart", () => {
    const p = buildPrompt("guide-section", { title: "T", text: SOURCE, part: 1, parts: 1 });
    expect(p.system).toMatch(/Do not name a subject/);
    expect(p.system).toMatch(/\[unclear\]/);
    expect(p.user).toContain('"type":"exercise"');
    expect(p.user).toMatch(/one "exercise" block per question, in the original order/);
  });

  it("truncates very long sources before they are sent to a model", () => {
    const p = buildPrompt("summary", { text: "a".repeat(50_000) });
    expect(p.user.length).toBeLessThan(14_000);
  });

  it("extracts JSON from fenced or chatty model output", () => {
    expect(extractJson('```json\n{"a":1}\n```')).toEqual({ a: 1 });
    expect(extractJson('Sure! Here you go: {"a":2} Hope that helps')).toEqual({ a: 2 });
    expect(() => extractJson("no json here")).toThrow(ProviderError);
  });

  it("validates quiz output and normalises string answers", () => {
    const r = parseTaskOutput("quiz", goodQuiz, "model-x");
    expect(r.task).toBe("quiz");
    if (r.task === "quiz") expect(r.value[0]?.correct).toEqual(["Chlorophyll"]);
  });

  it("rejects malformed structures with an invalid-output error", () => {
    expect(() => parseTaskOutput("quiz", JSON.stringify({ questions: [] }), "m")).toThrow(
      /expected format/,
    );
    expect(() => parseTaskOutput("cards", JSON.stringify({ cards: [{ front: "" }] }), "m")).toThrow(
      ProviderError,
    );
    expect(() => parseTaskOutput("notes", "{}", "m")).toThrow(ProviderError);
  });

  it("marks model-written notes as generated, with an honest notice", () => {
    const r = parseTaskOutput(
      "notes",
      JSON.stringify({
        summary: "S",
        definitions: [{ term: "T", definition: "D" }],
        sections: [{ heading: "H", body: "B" }],
      }),
      "model-x",
    );
    if (r.task !== "notes") throw new Error("wrong task");
    expect(r.value.definitions[0]?.provenance).toBe("generated");
    expect(r.value.sections[0]?.provenance).toBe("generated");
    expect(r.value.notices[0]).toMatch(/Generated by model-x/);
  });
});

describe("hosted provider client", () => {
  it("requires explicit consent before it can even be constructed", () => {
    expect(() => createHostedProvider(false)).toThrow(/permission/i);
  });

  it("only talks to Ghadi's own server route and sends consent", async () => {
    const fetchMock = vi.fn(
      async (..._a: unknown[]) =>
        new Response(JSON.stringify({ text: JSON.stringify({ text: "Short summary." }) })),
    );
    const p = createHostedProvider(true, "gpt-test", fetchMock as unknown as typeof fetch);
    const r = await p.summarizeContent({ title: "t", text: SOURCE });
    expect(r.origin).toBe("hosted-ai");
    expect(r.value).toBe("Short summary.");
    const [url, init] = fetchMock.mock.calls[0] as unknown as [string, RequestInit];
    expect(url).toBe("/api/ai/generate");
    expect(JSON.parse(init.body as string)).toMatchObject({ task: "summary", consent: true });
  });

  it("maps server errors to typed provider errors", async () => {
    const mk = (status: number) =>
      createHostedProvider(
        true,
        "m",
        (async () =>
          new Response(JSON.stringify({ error: { message: "nope" } }), {
            status,
          })) as unknown as typeof fetch,
      );
    await expect(mk(501).summarizeContent({ title: "t", text: SOURCE })).rejects.toMatchObject({
      code: "not-configured",
    });
    await expect(mk(429).summarizeContent({ title: "t", text: SOURCE })).rejects.toMatchObject({
      code: "rate-limited",
    });
  });
});

describe("OpenAI is the only engine; no silent fallback", () => {
  const consented = settingsSchema.parse({ hostedConsent: true });
  const noConsent = settingsSchema.parse({});
  const failing = (code: ProviderError["code"]) => async () => {
    throw new ProviderError(code, "OpenAI failed");
  };

  it("has no provider setting at all", () => {
    expect("provider" in settingsSchema.parse({})).toBe(false);
    expect("ollamaEndpoint" in settingsSchema.parse({})).toBe(false);
  });

  it("refuses to run without the learner's consent", async () => {
    await expect(
      generateWithFallback(noConsent, (p) => p.summarizeContent({ title: "t", text: SOURCE })),
    ).rejects.toMatchObject({ code: "consent-required" });
  });

  it("surfaces an OpenAI failure instead of producing offline output", async () => {
    await expect(generateWithFallback(consented, failing("rate-limited"))).rejects.toMatchObject({
      code: "rate-limited",
    });
  });

  it("uses the offline rules only when the user explicitly asks, and labels it", async () => {
    const r = await generateWithFallback(
      noConsent,
      (p) => p.summarizeContent({ title: "t", text: SOURCE }),
      { useOffline: true },
    );
    expect(r.origin).toBe("heuristic");
  });

  it("the explicit fallback flag says that OpenAI failed and the result is not AI", async () => {
    const calls: string[] = [];
    const r = await generateWithFallback(
      consented,
      async (p) => {
        calls.push(p.id);
        if (p.id === "hosted") throw new ProviderError("unreachable", "network down");
        return p.summarizeContent({ title: "t", text: SOURCE });
      },
      { allowOfflineFallback: true },
    );
    expect(calls).toEqual(["hosted", "offline"]);
    expect(r.origin).toBe("heuristic");
    expect(r.notices[0]).toMatch(/OpenAI could not be used.*no AI/);
  });

  it("never swallows user cancellation, even when fallback is allowed", async () => {
    await expect(
      generateWithFallback(consented, failing("cancelled"), { allowOfflineFallback: true }),
    ).rejects.toMatchObject({ code: "cancelled" });
  });
});

describe("hosted configuration (server side)", () => {
  it("is absent unless every variable is set, so the app starts without AI credentials", () => {
    expect(readHostedConfig({} as unknown as NodeJS.ProcessEnv)).toBeNull();
    expect(
      readHostedConfig({
        GHADI_HOSTED_AI_PROVIDER: "openai-compatible",
        GHADI_HOSTED_AI_BASE_URL: "https://api.example.com/v1",
      } as unknown as NodeJS.ProcessEnv),
    ).toBeNull();
    const cfg = readHostedConfig({
      GHADI_HOSTED_AI_PROVIDER: "openai-compatible",
      GHADI_HOSTED_AI_BASE_URL: "https://api.example.com/v1/",
      GHADI_HOSTED_AI_API_KEY: "placeholder-key",
      GHADI_HOSTED_AI_MODEL: "model-x",
    } as unknown as NodeJS.ProcessEnv);
    expect(cfg).toEqual({
      provider: "openai-compatible",
      baseUrl: "https://api.example.com/v1",
      apiKey: "placeholder-key",
      model: "model-x",
      visionModel: "model-x",
    });
  });

  it("supports OPENAI_API_KEY with an optional model and base URL", () => {
    const env = (e: Record<string, string>) => e as unknown as NodeJS.ProcessEnv;
    expect(readHostedConfig(env({ OPENAI_API_KEY: "sk-placeholder" }))).toEqual({
      provider: "openai",
      baseUrl: "https://api.openai.com/v1",
      apiKey: "sk-placeholder",
      model: "gpt-6-luna",
      visionModel: "gpt-6.1-sol",
    });
    expect(
      readHostedConfig(
        env({
          OPENAI_API_KEY: "k",
          OPENAI_MODEL: "gpt-5-mini",
          OPENAI_BASE_URL: "https://proxy.test/v1/",
        }),
      ),
    ).toMatchObject({ model: "gpt-5-mini", baseUrl: "https://proxy.test/v1" });
    expect(readHostedConfig(env({ OPENAI_API_KEY: "k", OPENAI_BASE_URL: "not a url" }))).toBeNull();
    expect(readHostedConfig(env({ OPENAI_API_KEY: "   " }))).toBeNull();
  });

  it("prefers the explicit GHADI_HOSTED_AI_* settings when both are present", () => {
    const cfg = readHostedConfig({
      GHADI_HOSTED_AI_PROVIDER: "openai-compatible",
      GHADI_HOSTED_AI_BASE_URL: "https://api.example.com/v1",
      GHADI_HOSTED_AI_API_KEY: "a",
      GHADI_HOSTED_AI_MODEL: "m",
      OPENAI_API_KEY: "b",
    } as unknown as NodeJS.ProcessEnv);
    expect(cfg?.apiKey).toBe("a");
  });
});
