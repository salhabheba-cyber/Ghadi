import { Badge } from "@/components/ui/primitives";
import type { Origin } from "@/lib/validation/schemas";

const LABELS: Record<
  Origin,
  { text: string; tone: "neutral" | "brand" | "warn" | "good"; title: string }
> = {
  manual: { text: "Written by you", tone: "good", title: "Created or edited manually" },
  heuristic: {
    text: "Offline heuristics",
    tone: "warn",
    title: "Built by rule-based text analysis. No AI model was used.",
  },
  "local-ai": {
    text: "Local AI",
    tone: "brand",
    title: "Generated by a model running on your computer",
  },
  "hosted-ai": { text: "Hosted AI", tone: "brand", title: "Generated by a hosted AI provider" },
};

export function OriginBadge({ origin }: { origin: Origin }) {
  const l = LABELS[origin];
  return (
    <span title={l.title}>
      <Badge tone={l.tone}>{l.text}</Badge>
    </span>
  );
}
