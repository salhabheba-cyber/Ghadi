import {
  ProviderError,
  type CallOptions,
  type CardDraft,
  type CardOptions,
  type Generated,
  type NoteDraft,
  type NoteOptions,
  type ProviderId,
  type QuestionDraft,
  type QuizOptions,
  type SourceInput,
  type StudyProvider,
  MAX_MODEL_INPUT_CHARS,
} from "./types";
import {
  buildPrompt,
  parseTaskOutput,
  type Prompt,
  type TaskName,
  type TaskPayload,
} from "./tasks";
import type { Origin } from "@/lib/validation/schemas";

export interface CompletionRequest {
  task: TaskName;
  payload: TaskPayload;
  prompt: Prompt;
}

/** Returns the model's raw text for a request. Implementations map transport failures to ProviderError. */
export type CompleteFn = (request: CompletionRequest, call: CallOptions) => Promise<string>;

/**
 * A StudyProvider backed by a text-completion function (the OpenAI route via createHostedProvider).
 */
export class LlmProvider implements StudyProvider {
  constructor(
    readonly id: ProviderId,
    readonly label: string,
    readonly origin: Origin,
    private readonly modelLabel: string,
    private readonly complete: CompleteFn,
  ) {}

  private async run<T extends TaskName>(task: T, payload: TaskPayload, call: CallOptions = {}) {
    const prompt = buildPrompt(task, payload);
    let lastError: unknown;
    // One retry when the model returns malformed output; transport errors are not retried.
    for (let attempt = 0; attempt < 2; attempt++) {
      const raw = await this.complete({ task, payload, prompt }, call);
      try {
        return parseTaskOutput(task, raw, this.modelLabel);
      } catch (error) {
        lastError = error;
        if (!(error instanceof ProviderError) || error.code !== "invalid-output") throw error;
      }
    }
    throw lastError;
  }

  private truncationNotice(text: string): string[] {
    return text.length > MAX_MODEL_INPUT_CHARS
      ? [
          `Only the first ${MAX_MODEL_INPUT_CHARS.toLocaleString()} characters of the source were sent to the model.`,
        ]
      : [];
  }

  async generateStudyNotes(
    input: SourceInput,
    options: NoteOptions,
    call?: CallOptions,
  ): Promise<Generated<NoteDraft>> {
    const result = await this.run(
      "notes",
      { title: input.title, text: input.text, language: options.language },
      call,
    );
    if (result.task !== "notes") throw new ProviderError("bad-response", "Unexpected result type.");
    const extra = this.truncationNotice(input.text);
    return {
      value: { ...result.value, notices: [...result.value.notices, ...extra] },
      origin: this.origin,
      notices: [...result.value.notices, ...extra],
    };
  }

  async generateQuiz(
    input: SourceInput,
    options: QuizOptions,
    call?: CallOptions,
  ): Promise<Generated<QuestionDraft[]>> {
    const result = await this.run(
      "quiz",
      {
        title: input.title,
        text: input.text,
        topic: input.topic,
        language: options.language,
        count: options.count,
        difficulty: options.difficulty,
        types: options.types,
      },
      call,
    );
    if (result.task !== "quiz") throw new ProviderError("bad-response", "Unexpected result type.");
    return {
      value: result.value.slice(0, options.count),
      origin: this.origin,
      notices: [
        input.topic
          ? `Generated by ${this.modelLabel} from its general knowledge of “${input.topic}”, not from a source document. Check it before relying on it.`
          : `Generated by ${this.modelLabel}. AI questions can be wrong: review them before relying on them.`,
        ...this.truncationNotice(input.text),
      ],
    };
  }

  async generateFlashcards(
    input: SourceInput,
    options: CardOptions,
    call?: CallOptions,
  ): Promise<Generated<CardDraft[]>> {
    const result = await this.run(
      "cards",
      { title: input.title, text: input.text, language: options.language, count: options.count },
      call,
    );
    if (result.task !== "cards") throw new ProviderError("bad-response", "Unexpected result type.");
    return {
      value: result.value.slice(0, options.count),
      origin: this.origin,
      notices: [
        `Generated by ${this.modelLabel}. Review the cards before studying.`,
        ...this.truncationNotice(input.text),
      ],
    };
  }

  async explainAnswer(
    input: { question: string; correctAnswer: string; userAnswer: string; sourceExcerpt?: string },
    call?: CallOptions,
  ): Promise<Generated<string>> {
    const result = await this.run("explain", input, call);
    if (result.task !== "explain")
      throw new ProviderError("bad-response", "Unexpected result type.");
    return {
      value: result.value,
      origin: this.origin,
      notices: [`Explanation written by ${this.modelLabel}.`],
    };
  }

  async summarizeContent(input: SourceInput, call?: CallOptions): Promise<Generated<string>> {
    const result = await this.run("summary", { title: input.title, text: input.text }, call);
    if (result.task !== "summary")
      throw new ProviderError("bad-response", "Unexpected result type.");
    return {
      value: result.value,
      origin: this.origin,
      notices: [`Summary written by ${this.modelLabel}.`, ...this.truncationNotice(input.text)],
    };
  }

  /** One chunk of a long document -> teaching sections. Used by the study-guide pipeline. */
  async generateGuideSections(
    input: { title: string; text: string; part: number; parts: number; language: string },
    call?: CallOptions,
  ) {
    const result = await this.run(
      "guide-section",
      {
        title: input.title,
        text: input.text,
        part: input.part,
        parts: input.parts,
        language: input.language,
      },
      call,
    );
    if (result.task !== "guide-section")
      throw new ProviderError("bad-response", "Unexpected result type.");
    return result.value;
  }

  /** Overview, objectives and final summary written from the section headings and recaps only. */
  async generateGuideOverview(
    input: { title: string; recaps: string; language: string },
    call?: CallOptions,
  ) {
    const result = await this.run(
      "guide-overview",
      { title: input.title, text: input.recaps, language: input.language },
      call,
    );
    if (result.task !== "guide-overview")
      throw new ProviderError("bad-response", "Unexpected result type.");
    return result.value;
  }

  async simplify(
    input: { concept: string; context?: string; language: string },
    call?: CallOptions,
  ): Promise<string> {
    const result = await this.run(
      "simplify",
      { concept: input.concept, sourceExcerpt: input.context, language: input.language },
      call,
    );
    if (result.task !== "simplify")
      throw new ProviderError("bad-response", "Unexpected result type.");
    return result.value;
  }
}
