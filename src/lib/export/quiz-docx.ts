/**
 * Generates a .docx quiz sheet from quiz data using the `docx` library.
 */

import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  AlignmentType,
  BorderStyle,
} from "docx";

export interface ExportQuestion {
  type: "mcq" | "tf" | "short" | "fill";
  prompt: string;
  options?: string[];
  correct: string[];
  explanation?: string;
}

export interface QuizExportData {
  title: string;
  subject?: string;
  generatedAt?: string;
  questions: ExportQuestion[];
  includeAnswers: boolean;
}

const BRAND_COLOR = "7C3AED"; // Ghadi purple

function makeHeading(
  text: string,
  level: (typeof HeadingLevel)[keyof typeof HeadingLevel] = HeadingLevel.HEADING_1,
) {
  return new Paragraph({
    heading: level,
    children: [new TextRun({ text, bold: true, color: BRAND_COLOR })],
  });
}

function makeSpacer() {
  return new Paragraph({ text: "" });
}

function makeQuestionBlock(q: ExportQuestion, idx: number, includeAnswers: boolean): Paragraph[] {
  const blocks: Paragraph[] = [];

  // Question number + prompt
  const prefix = q.type === "fill" ? "Fill in the blank" : "";
  blocks.push(
    new Paragraph({
      children: [
        new TextRun({ text: `${idx + 1}. `, bold: true }),
        new TextRun({ text: q.prompt }),
        prefix
          ? new TextRun({ text: `  [${prefix}]`, italics: true, color: "888888" })
          : new TextRun(""),
      ],
      spacing: { before: 200 },
    }),
  );

  // Fill-in-blank: blank line for writing
  if (q.type === "fill" || q.type === "short") {
    blocks.push(
      new Paragraph({
        children: [
          new TextRun({ text: "Answer: _______________________________________________" }),
        ],
        indent: { left: 400 },
      }),
    );
  }

  // MCQ / TF options
  if (q.options && q.options.length > 0) {
    const letters = ["A", "B", "C", "D", "E"];
    q.options.forEach((opt, i) => {
      blocks.push(
        new Paragraph({
          children: [
            new TextRun({ text: `${letters[i] ?? String(i + 1)}. ` }),
            new TextRun({ text: opt }),
          ],
          indent: { left: 400 },
        }),
      );
    });
  }

  // Answer key (if requested)
  if (includeAnswers) {
    blocks.push(
      new Paragraph({
        children: [
          new TextRun({ text: "✓ Answer: ", bold: true, color: "16A34A" }),
          new TextRun({ text: q.correct.join(" / "), color: "16A34A" }),
        ],
        indent: { left: 400 },
      }),
    );
    if (q.explanation) {
      blocks.push(
        new Paragraph({
          children: [
            new TextRun({ text: "Explanation: ", italics: true, color: "555555" }),
            new TextRun({ text: q.explanation, italics: true, color: "555555" }),
          ],
          indent: { left: 400 },
        }),
      );
    }
  }

  return blocks;
}

export async function buildQuizDocx(data: QuizExportData): Promise<Buffer> {
  const now = data.generatedAt ?? new Date().toLocaleDateString("en-GB");

  const headerSection: Paragraph[] = [
    makeHeading(`📚 ${data.title}`),
    new Paragraph({
      children: [
        new TextRun({ text: data.subject ? `Subject: ${data.subject}  |  ` : "" }),
        new TextRun({ text: `Generated by Ghadi · ${now}` }),
        data.includeAnswers
          ? new TextRun({ text: "  |  Answer Key Included", bold: true, color: BRAND_COLOR })
          : new TextRun(""),
      ],
      alignment: AlignmentType.LEFT,
    }),
    makeSpacer(),
    new Paragraph({
      border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: BRAND_COLOR } },
      text: "",
    }),
    makeSpacer(),
  ];

  const questionBlocks = data.questions.flatMap((q, i) => [
    ...makeQuestionBlock(q, i, data.includeAnswers),
    makeSpacer(),
  ]);

  const footerSection: Paragraph[] = [
    makeSpacer(),
    new Paragraph({
      border: { top: { style: BorderStyle.SINGLE, size: 4, color: "CCCCCC" } },
      children: [
        new TextRun({
          text: "Generated with Ghadi — Free AI-Powered Learning Platform · ghadi.app",
          color: "888888",
          size: 18,
        }),
      ],
      alignment: AlignmentType.CENTER,
    }),
  ];

  const doc = new Document({
    creator: "Ghadi",
    title: data.title,
    description: `Quiz generated by Ghadi — ${data.questions.length} questions`,
    styles: {
      default: {
        document: {
          run: { font: "Calibri", size: 24 },
        },
      },
    },
    sections: [
      {
        children: [...headerSection, ...questionBlocks, ...footerSection],
      },
    ],
  });

  return Packer.toBuffer(doc);
}
