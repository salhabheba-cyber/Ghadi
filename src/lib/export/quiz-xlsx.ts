/**
 * Generates a structured .xlsx quiz workbook using ExcelJS.
 *
 * Worksheets:
 *   1. "Questions"    — numbered questions with answer blanks; options listed for MCQ/TF
 *   2. "Answer Key"   — correct answers column-aligned with questions (optional)
 *   3. "Grading Table" — one row per question, student-name column, answer column, mark column
 *
 * The workbook never places the entire exam in a single unformatted cell.
 */

import ExcelJS from "exceljs";
import type { ExportQuestion } from "./quiz-docx";

export interface XlsxExportOptions {
  title: string;
  subject?: string;
  generatedAt?: string;
  questions: ExportQuestion[];
  /** Include a dedicated Answer Key sheet */
  includeAnswerKey: boolean;
  /** Include explanations in the Answer Key sheet */
  includeExplanations?: boolean;
  /** Student name/class/date fields on the Questions sheet */
  studentFields?: boolean;
}

const BRAND_ARGB = "FF7C3AED"; // Ghadi violet
const BRAND_LIGHT_ARGB = "FFF3EFFE"; // soft lavender
const CORRECT_ARGB = "FF16A34A"; // green
const MUTED_ARGB = "FF6B7280"; // grey
const LETTERS = ["A", "B", "C", "D", "E", "F", "G", "H"];

function applyHeaderStyle(row: ExcelJS.Row, bgArgb: string = BRAND_ARGB) {
  row.eachCell((cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: bgArgb } };
    cell.font = {
      bold: true,
      color: { argb: bgArgb === BRAND_ARGB ? "FFFFFFFF" : "FF1F1F2E" },
      size: 11,
    };
    cell.alignment = { vertical: "middle", wrapText: true };
    cell.border = {
      bottom: { style: "thin", color: { argb: BRAND_ARGB } },
    };
  });
  row.height = 24;
}

function applySubtleRow(row: ExcelJS.Row) {
  row.eachCell((cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND_LIGHT_ARGB } };
    cell.alignment = { vertical: "middle", wrapText: true };
  });
}

/** Build the "Questions" worksheet */
function buildQuestionsSheet(wb: ExcelJS.Workbook, data: XlsxExportOptions): void {
  const ws = wb.addWorksheet("Questions");

  // ── Column widths ──
  ws.columns = [
    { key: "no", width: 6 },
    { key: "type", width: 10 },
    { key: "question", width: 56 },
    { key: "answer", width: 36 },
  ];

  // ── Title block ──
  const titleRow = ws.addRow([data.title]);
  titleRow.getCell(1).font = { bold: true, size: 16, color: { argb: BRAND_ARGB } };
  titleRow.getCell(1).alignment = { horizontal: "left", vertical: "middle" };
  titleRow.height = 32;
  ws.mergeCells(`A${titleRow.number}:D${titleRow.number}`);

  if (data.subject) {
    const subRow = ws.addRow([`Subject: ${data.subject}`]);
    subRow.getCell(1).font = { italic: true, color: { argb: MUTED_ARGB } };
    ws.mergeCells(`A${subRow.number}:D${subRow.number}`);
  }

  const metaRow = ws.addRow([
    `Generated by Ghadi · ${data.generatedAt ?? new Date().toLocaleDateString("en-GB")}`,
  ]);
  metaRow.getCell(1).font = { color: { argb: MUTED_ARGB }, size: 9 };
  ws.mergeCells(`A${metaRow.number}:D${metaRow.number}`);

  ws.addRow([]); // spacer

  // ── Student fields ──
  if (data.studentFields) {
    const fields = [
      ["Name:", ""],
      ["Class:", ""],
      ["Date:", ""],
    ];
    for (const [label, value] of fields) {
      const row = ws.addRow([label, value]);
      row.getCell(1).font = { bold: true };
      row.getCell(2).border = { bottom: { style: "thin" } };
      row.getCell(2).alignment = { horizontal: "left" };
    }
    ws.addRow([]); // spacer
  }

  // ── Column headings ──
  const headerRow = ws.addRow(["#", "Type", "Question", "Your Answer"]);
  applyHeaderStyle(headerRow);

  // ── Questions ──
  for (let i = 0; i < data.questions.length; i++) {
    const q = data.questions[i]!;

    const typeLabel: Record<string, string> = {
      mcq: "MCQ",
      tf: "True/False",
      fill: "Fill-in",
      short: "Short Ans.",
    };

    // Question row
    const qRow = ws.addRow([i + 1, typeLabel[q.type] ?? q.type, q.prompt, ""]);
    qRow.getCell(1).font = { bold: true };
    qRow.getCell(3).alignment = { wrapText: true, vertical: "top" };
    qRow.getCell(4).border = { bottom: { style: "thin" } };
    qRow.height = Math.min(80, 18 + Math.floor(q.prompt.length / 70) * 14);

    if (i % 2 === 0) applySubtleRow(qRow);

    // MCQ / TF options — each on its own indented row
    if (q.options && q.options.length > 0) {
      for (let j = 0; j < q.options.length; j++) {
        const optRow = ws.addRow(["", "", `  ${LETTERS[j] ?? j + 1}.  ${q.options[j]}`, ""]);
        optRow.getCell(3).font = { color: { argb: "FF374151" } };
        optRow.getCell(3).alignment = { indent: 2, wrapText: true };
        if (i % 2 === 0) {
          optRow.getCell(3).fill = {
            type: "pattern",
            pattern: "solid",
            fgColor: { argb: BRAND_LIGHT_ARGB },
          };
        }
        optRow.height = 16;
      }
    }

    // Fill/short: explicit answer line
    if (q.type === "fill" || q.type === "short") {
      const ansRow = ws.addRow(["", "", "  Answer: ______________________________________", ""]);
      ansRow.getCell(3).font = { color: { argb: MUTED_ARGB } };
      if (i % 2 === 0) applySubtleRow(ansRow);
    }
  }

  // ── Footer ──
  ws.addRow([]);
  const ftRow = ws.addRow(["Generated with Ghadi — Learn Smarter. Remember More. Stay Free."]);
  ftRow.getCell(1).font = { color: { argb: MUTED_ARGB }, size: 8, italic: true };
  ws.mergeCells(`A${ftRow.number}:D${ftRow.number}`);
}

/** Build the "Answer Key" worksheet */
function buildAnswerKeySheet(wb: ExcelJS.Workbook, data: XlsxExportOptions): void {
  const ws = wb.addWorksheet("Answer Key");

  ws.columns = [
    { key: "no", width: 6 },
    { key: "type", width: 10 },
    { key: "question", width: 48 },
    { key: "answer", width: 28 },
    { key: "explanation", width: 40 },
  ];

  const titleRow = ws.addRow([`${data.title} — Answer Key`]);
  titleRow.getCell(1).font = { bold: true, size: 14, color: { argb: BRAND_ARGB } };
  ws.mergeCells(`A${titleRow.number}:E${titleRow.number}`);
  titleRow.height = 28;
  ws.addRow([]);

  const colCount = data.includeExplanations ? 5 : 4;
  const headerCells = data.includeExplanations
    ? ["#", "Type", "Question", "Correct Answer", "Explanation"]
    : ["#", "Type", "Question", "Correct Answer"];
  const headerRow = ws.addRow(headerCells);
  applyHeaderStyle(headerRow);

  const typeLabel: Record<string, string> = {
    mcq: "MCQ",
    tf: "True/False",
    fill: "Fill-in",
    short: "Short Ans.",
  };

  for (let i = 0; i < data.questions.length; i++) {
    const q = data.questions[i]!;
    const cells: (string | number)[] = [
      i + 1,
      typeLabel[q.type] ?? q.type,
      q.prompt,
      q.correct.join(" / "),
    ];
    if (data.includeExplanations) cells.push(q.explanation ?? "");
    const row = ws.addRow(cells);
    row.getCell(1).font = { bold: true };
    row.getCell(4).font = { bold: true, color: { argb: CORRECT_ARGB } };
    if (data.includeExplanations) {
      row.getCell(5).font = { italic: true, color: { argb: MUTED_ARGB } };
    }
    row.eachCell((cell) => {
      cell.alignment = { wrapText: true, vertical: "top" };
    });
    row.height = Math.min(80, 18 + Math.floor(q.prompt.length / 60) * 14);
    if (i % 2 === 0) {
      for (let c = 1; c <= colCount; c++) {
        row.getCell(c).fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: BRAND_LIGHT_ARGB },
        };
      }
    }
  }

  ws.addRow([]);
  const ftRow = ws.addRow(["Generated with Ghadi — ghadi.app"]);
  ftRow.getCell(1).font = { color: { argb: MUTED_ARGB }, size: 8 };
  ws.mergeCells(`A${ftRow.number}:${String.fromCharCode(64 + colCount)}${ftRow.number}`);
}

/** Build the "Grading Table" worksheet (for teachers/instructors) */
function buildGradingTableSheet(wb: ExcelJS.Workbook, data: XlsxExportOptions): void {
  const ws = wb.addWorksheet("Grading Table");

  ws.columns = [
    { key: "no", width: 6 },
    { key: "question", width: 40 },
    { key: "student_answer", width: 30 },
    { key: "correct_answer", width: 24 },
    { key: "marks", width: 12 },
    { key: "notes", width: 24 },
  ];

  const titleRow = ws.addRow([`${data.title} — Grading Table`]);
  titleRow.getCell(1).font = { bold: true, size: 14, color: { argb: BRAND_ARGB } };
  ws.mergeCells(`A${titleRow.number}:F${titleRow.number}`);
  titleRow.height = 28;

  ws.addRow(["Student Name:", "___________________________"]);
  ws.addRow(["Class:", "___________________________"]);
  ws.addRow([]);

  const headerRow = ws.addRow([
    "#",
    "Question",
    "Student Answer",
    "Correct Answer",
    "Marks",
    "Notes",
  ]);
  applyHeaderStyle(headerRow);

  const typeLabel: Record<string, string> = {
    mcq: "MCQ",
    tf: "T/F",
    fill: "Fill",
    short: "Short",
  };

  for (let i = 0; i < data.questions.length; i++) {
    const q = data.questions[i]!;
    const prompt = q.options
      ? `[${typeLabel[q.type]}] ${q.prompt}\n${q.options.map((o, j) => `  ${LETTERS[j]}. ${o}`).join("\n")}`
      : `[${typeLabel[q.type]}] ${q.prompt}`;
    const row = ws.addRow([i + 1, prompt, "", q.correct.join(" / "), "", ""]);
    row.getCell(1).font = { bold: true };
    row.getCell(4).font = { color: { argb: CORRECT_ARGB } };
    row.getCell(3).border = { bottom: { style: "thin" } };
    row.getCell(5).border = { bottom: { style: "thin" } };
    row.getCell(6).border = { bottom: { style: "thin" } };
    row.eachCell((cell) => {
      cell.alignment = { wrapText: true, vertical: "top" };
    });
    row.height = Math.min(80, 18 + prompt.split("\n").length * 14);
    if (i % 2 === 0) {
      for (let c = 1; c <= 6; c++) {
        row.getCell(c).fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: BRAND_LIGHT_ARGB },
        };
      }
    }
  }

  // Total row
  ws.addRow([]);
  const totalRow = ws.addRow(["", "Total", "", "", `=SUM(E6:E${5 + data.questions.length})`, ""]);
  totalRow.getCell(2).font = { bold: true };
  totalRow.getCell(5).font = { bold: true, color: { argb: BRAND_ARGB } };
  totalRow.getCell(5).border = { top: { style: "double", color: { argb: BRAND_ARGB } } };
}

/** Build a complete quiz workbook and return it as a Buffer */
export async function buildQuizXlsx(options: XlsxExportOptions): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "Ghadi";
  wb.lastModifiedBy = "Ghadi";
  wb.created = new Date();
  wb.modified = new Date();
  wb.properties.date1904 = false;

  buildQuestionsSheet(wb, options);
  if (options.includeAnswerKey) {
    buildAnswerKeySheet(wb, options);
  }
  buildGradingTableSheet(wb, options);

  const buf = await wb.xlsx.writeBuffer();
  return Buffer.from(buf);
}
