import type { Card, Deck, Note, Quiz } from "@/lib/validation/schemas";

/** Neutralises spreadsheet formula injection in CSV cells (=, +, -, @, tab, CR at the start). */
export function csvCell(value: string): string {
  let v = value.replace(/\r?\n/g, " ");
  if (/^[=+\-@\t\r]/.test(v)) v = `'${v}`;
  return `"${v.replace(/"/g, '""')}"`;
}

export function toCsv(rows: string[][]): string {
  return rows.map((r) => r.map(csvCell).join(",")).join("\r\n") + "\r\n";
}

const originLine = (o: Note["origin"]) =>
  o === "heuristic"
    ? "_Generated by offline heuristics. No AI model was used._"
    : o === "manual"
      ? "_Written by hand._"
      : `_Generated with ${o === "local-ai" ? "a local AI model" : "a hosted AI provider"}. Check it against your source._`;

export function noteToMarkdown(note: Note): string {
  const out: string[] = [`# ${note.title}`, "", originLine(note.origin), ""];
  for (const n of note.notices) out.push(`> ${n}`);
  if (note.notices.length) out.push("");
  if (note.overview) out.push("## Overview", "", note.overview, "");
  if (note.summary) out.push("## Summary", "", note.summary, "");
  if (note.keyConcepts.length)
    out.push("## Key concepts", "", ...note.keyConcepts.map((k) => `- ${k}`), "");
  if (note.definitions.length)
    out.push(
      "## Definitions",
      "",
      ...note.definitions.map((d) => `- **${d.term}**: ${d.definition}`),
      "",
    );
  for (const s of note.sections) out.push(`## ${s.heading}`, "", s.body, "");
  if (note.facts.length)
    out.push(
      "## Dates and formulas",
      "",
      ...note.facts.map((f) => `- ${f.value}${f.context ? ` — ${f.context}` : ""}`),
      "",
    );
  if (note.examples.length)
    out.push("## Examples", "", ...note.examples.map((e) => `- ${e.text}`), "");
  if (note.relationships.length)
    out.push("## Related ideas", "", ...note.relationships.map((r) => `- ${r}`), "");
  if (note.checklist.length)
    out.push(
      "## Review checklist",
      "",
      ...note.checklist.map((c) => `- [${c.done ? "x" : " "}] ${c.text}`),
      "",
    );
  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

export function quizToMarkdown(quiz: Quiz, withAnswers = true): string {
  const out: string[] = [`# ${quiz.title}`, ""];
  quiz.questions.forEach((q, i) => {
    out.push(`${i + 1}. ${q.prompt}`);
    q.options?.forEach((o, j) => out.push(`   ${String.fromCharCode(97 + j)}) ${o}`));
    if (withAnswers) {
      out.push(`   **Answer:** ${q.correct.join(" / ")}`);
      if (q.explanation) out.push(`   _${q.explanation}_`);
    }
    out.push("");
  });
  return out.join("\n");
}

export function deckToCsv(cards: Pick<Card, "front" | "back" | "explanation">[]): string {
  return toCsv([
    ["Front", "Back", "Explanation"],
    ...cards.map((c) => [c.front, c.back, c.explanation ?? ""]),
  ]);
}

export function deckToMarkdown(deck: Deck, cards: Pick<Card, "front" | "back">[]): string {
  return [
    `# ${deck.title}`,
    "",
    ...cards.flatMap((c) => [`**Q:** ${c.front}`, "", `**A:** ${c.back}`, ""]),
  ].join("\n");
}

const WINDOWS_RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;

/** Builds a download name from user text: no separators, no leading dots, no reserved device names. */
export function safeFileName(name: string, ext: string): string {
  let base = name
    .replace(/[^\p{L}\p{N}._ -]+/gu, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/\.{2,}/g, ".")
    .replace(/^[.\-]+|[.\- ]+$/g, "")
    .slice(0, 80);
  if (!base || WINDOWS_RESERVED.test(base)) base = "ghadi";
  return `${base}.${ext}`;
}

/** Triggers a browser download of text content. */
export function downloadText(fileName: string, content: string, mime = "text/plain"): void {
  const url = URL.createObjectURL(new Blob([content], { type: `${mime};charset=utf-8` }));
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
